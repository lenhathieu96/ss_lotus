import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const contractVersion = 1;

/** Hash deployable bytes with length framing so file boundaries are unambiguous. */
export async function computeReleaseId(root = projectRoot) {
  const directory = join(root, 'supabase/functions/library-lifecycle');
  const files = [];
  async function walk(path) {
    for (const entry of await readdir(path, { withFileTypes: true })) {
      if (entry.name === 'node_modules' || entry.name === '.DS_Store') continue;
      const target = join(path, entry.name);
      if (entry.isDirectory()) await walk(target);
      else if (entry.isFile() && entry.name !== 'build-info.ts' && !/\.(test|spec)\.[cm]?[jt]s$/.test(entry.name)) files.push(target);
      else if (entry.isSymbolicLink()) throw new Error('Function artifacts must not contain symbolic links.');
    }
  }
  await walk(directory);
  for (const required of ['index.ts', 'deno.json', 'deno.lock']) {
    if (!files.includes(join(directory, required))) throw new Error(`Missing function artifact: ${required}`);
  }
  const hash = createHash('sha256');
  function frame(label, bytes) {
    hash.update(`${Buffer.byteLength(label)}:${label}:${bytes.length}:`);
    hash.update(bytes);
  }
  frame('contractVersion', Buffer.from(String(contractVersion)));
  for (const file of files.sort()) {
    frame(relative(root, file).replaceAll('\\', '/'), await readFile(file));
  }
  const config = await readFile(join(root, 'supabase/config.toml'), 'utf8');
  // Only this function's section changes its gateway and packaging contract.
  const section = config.match(/^\[functions\.library-lifecycle\][^]*?(?=^\[|$(?![^]))/m)?.[0];
  if (!section) throw new Error('Missing library-lifecycle function configuration.');
  frame('supabase/config.toml#functions.library-lifecycle', Buffer.from(section.trim()));
  return `sha256:${hash.digest('hex')}`;
}

export async function writeBuildInfo(root = projectRoot) {
  const releaseId = await computeReleaseId(root);
  await writeFile(join(root, 'supabase/functions/library-lifecycle/build-info.ts'),
    `// Generated by scripts/library-function-release-id.mjs; do not edit.\nexport const buildInfo = ${JSON.stringify({ contractVersion, releaseId })} as const;\n`);
  return releaseId;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  try {
    const args = process.argv.slice(2);
    if (args.some(arg => arg !== '--write-build-info')) throw new Error('Usage: library-function-release-id.mjs [--write-build-info]');
    console.log(await (args.includes('--write-build-info') ? writeBuildInfo() : computeReleaseId()));
  } catch (error) { console.error(error.message); process.exitCode = 1; }
}
